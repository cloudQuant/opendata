_INTEGER_LIST = re.compile(r"[0-9]+(?:,[0-9]+)*\Z")
_GROUP_API_VALUE = dict(GROUP_VALUES)


_QUERY_FIELDS = frozenset(parameter.name for parameter in ECONOMIC_CALENDAR.params) | {
    "source",
    "market",
}


def _query_validation_error(*names: str) -> ValidationError:
    """Build a Pydantic query error that contains field names, never caller values."""
    locations = sorted({name if name in _QUERY_FIELDS else "query" for name in names}) or ["query"]
    return ValidationError.from_exception_data(
        "EconomicCalendarQuery",
        [
            {
                "type": "value_error",
                "loc": (name,),
                "input": None,
                "ctx": {"error": ValueError("invalid query")},
            }
            for name in locations
        ],
    )


def _sanitized_query_validation_error(error: ValidationError) -> ValidationError:
    """Keep useful field locations from generated validation without retaining inputs."""
    names: set[str] = set()
    for detail in error.errors():
        location = detail.get("loc", ())
        if location:
            name = str(location[0])
            names.add(name if name in _QUERY_FIELDS else "query")
    return _query_validation_error(*sorted(names))


def _request_route(params: object) -> tuple[str, tuple[str, ...]]:
    """Choose a URL path from combinations documented by Trading Economics."""
    country = getattr(params, "country", None)
    group = getattr(params, "group", None)
    start_date = getattr(params, "start_date", None)
    end_date = getattr(params, "end_date", None)
    importance = getattr(params, "importance", None)
    calendar_id = getattr(params, "calendar_id", None)

    if calendar_id:
        return f"/calendar/calendarid/{quote(calendar_id, safe=',')}", (
            "calendar_id",
            "country",
            "start_date",
            "end_date",
            "group",
        )

    path = "/calendar"
    consumed: list[str] = []
    if country and group:
        group_path = quote(_GROUP_API_VALUE[group], safe="")
        country_path = quote(country, safe=",")
        path = f"/calendar/country/{country_path}/group/{group_path}"
        consumed.extend(("country", "group"))
        if start_date and end_date:
            path += f"/{start_date.isoformat()}/{end_date.isoformat()}"
            consumed.extend(("start_date", "end_date"))
    elif group:
        group_path = quote(_GROUP_API_VALUE[group], safe="")
        path = f"/calendar/group/{group_path}"
        consumed.append("group")
        if start_date and end_date:
            path += f"/{start_date.isoformat()}/{end_date.isoformat()}"
            consumed.extend(("start_date", "end_date"))
    elif country or importance:
        country_path = quote(country or "All", safe=",")
        path = f"/calendar/country/{country_path}"
        if country:
            consumed.append("country")
        if start_date and end_date:
            path += f"/{start_date.isoformat()}/{end_date.isoformat()}"
            consumed.extend(("start_date", "end_date"))
    elif start_date and end_date:
        path = f"/calendar/country/All/{start_date.isoformat()}/{end_date.isoformat()}"
        consumed.extend(("start_date", "end_date"))

    return path, tuple(consumed)


def _integer_or_null(record: dict[str, Any], key: str) -> None:
    """Normalize a documented digit-string field without guessing at malformed values."""
    value = record.get(key)
    if isinstance(value, str):
        if value.strip() == "" or value.casefold() == "null":
            record[key] = None
        elif value.isdecimal():
            record[key] = int(value)


def _adapt_record(record: object) -> object:
    """Map documented TE JSON spellings into the OpenBB output value types."""
    if not isinstance(record, dict):
        return record
    adapted = dict(record)
    for key in ("CalendarId", "DateSpan"):
        _integer_or_null(adapted, key)

    source_date = adapted.get("Date")
    if isinstance(source_date, str):
        try:
            parsed_date = datetime.fromisoformat(source_date.replace("Z", "+00:00"))
        except ValueError:
            pass
        else:
            if parsed_date.tzinfo is None:
                parsed_date = parsed_date.replace(tzinfo=timezone.utc)
            else:
                parsed_date = parsed_date.astimezone(timezone.utc)
            adapted["Date"] = parsed_date

    importance = adapted.get("Importance")
    importance_labels: dict[int | str, str] = {
        1: "low",
        2: "medium",
        3: "high",
        "1": "low",
        "2": "medium",
        "3": "high",
    }
    if not isinstance(importance, bool) and importance in importance_labels:
        adapted["Importance"] = importance_labels[importance]

    reference_date = adapted.get("ReferenceDate")
    if isinstance(reference_date, str):
        if reference_date.strip() == "" or reference_date.casefold() == "null":
            adapted["ReferenceDate"] = None
        else:
            with suppress(ValueError):
                adapted["ReferenceDate"] = date.fromisoformat(reference_date[:10])

    return adapted


def _adapt_document(document: object) -> object:
    """Keep non-list bodies intact for the engine's fail-closed shape check."""
    if not isinstance(document, list):
        return document
    if len(document) > TRADINGECONOMICS_CALENDAR_MAX_ROWS:
        raise ProviderEngineError("TRADINGECONOMICS_ROW_LIMIT")
    return [_adapt_record(record) for record in document]


def _request_spec(params: object) -> ModelSpec:
    """Build the endpoint declaration after moving documented filters into its path."""
    path, consumed = _request_route(params)
    return replace(
        ECONOMIC_CALENDAR,
        path=path,
        params=tuple(
            parameter for parameter in ECONOMIC_CALENDAR.params if parameter.name not in consumed
        ),
    )


def _request_url_length(params: object, spec: ModelSpec) -> int:
    """Measure the exact encoded URL, including query parameters and the credential."""
    request_params = encode_query(params, spec)
    if spec.credential:
        request_params[spec.credential_query_key or "api_key"] = _credential_value(spec)
    url = f"{spec.base_url.rstrip('/')}{render_path(spec, params)}"
    if request_params:
        url += "?" + urlencode(request_params)
    return len(url)


def _calendar_id_batches(
    params: _EconomicCalendarQuery,
) -> tuple[_EconomicCalendarQuery, ...]:
    """Split comma-separated calendar IDs into paths within the documented URL ceiling."""
    calendar_id = params.calendar_id
    if calendar_id is None:
        raise _query_validation_error("calendar_id")
    identifiers = calendar_id.split(",")
    batches: list[_EconomicCalendarQuery] = []
    current: list[str] = []
    for identifier in identifiers:
        candidate = current + [identifier]
        candidate_params = params.model_copy(update={"calendar_id": ",".join(candidate)})
        if _request_url_length(candidate_params, _request_spec(candidate_params)) <= (
            TRADINGECONOMICS_MAX_URL_CHARS
        ):
            current = candidate
            continue
        if not current:
            raise _query_validation_error("calendar_id")
        batches.append(params.model_copy(update={"calendar_id": ",".join(current)}))
        current = [identifier]
        single_params = params.model_copy(update={"calendar_id": identifier})
        if _request_url_length(single_params, _request_spec(single_params)) > (
            TRADINGECONOMICS_MAX_URL_CHARS
        ):
            raise _query_validation_error("calendar_id")
    if current:
        batches.append(params.model_copy(update={"calendar_id": ",".join(current)}))
    return tuple(batches)


class TradingEconomicsEconomicCalendarFetcher(_GeneratedCalendarFetcher):
    """Economic-calendar fetcher using the source's explicitly documented route variants."""

    http_transport: ClassVar[HttpGet | None] = None

    def transform_query(self, **kwargs: object) -> _EconomicCalendarQuery:
        """Validate injected identity, then the strict business query.

        ``provider_model_query`` pins ``source`` and ``market`` from the registry before invoking
        a fetcher. They are routing identity, not Trading Economics request parameters, so accept
        only this binding's exact values and remove them before the generated model validates the
        declared upstream query.
        """
        normalized = dict(kwargs)
        for name, expected in (("source", SOURCE), ("market", ECONOMIC_CALENDAR.market)):
            if name not in normalized:
                continue
            value = normalized.pop(name)
            if type(value) is not str or value != expected:
                raise _query_validation_error(name)

        calendar_id = normalized.get("calendar_id")
        if isinstance(calendar_id, int) and not isinstance(calendar_id, bool):
            normalized["calendar_id"] = str(calendar_id)
        try:
            params = self.query_model.model_validate(normalized)
        except ValidationError as exc:
            raise _sanitized_query_validation_error(exc) from None

        start_date = params.start_date
        end_date = params.end_date
        if (start_date is None) != (end_date is None):
            raise _query_validation_error("start_date", "end_date")
        if start_date is not None and end_date is not None and start_date > end_date:
            raise _query_validation_error("start_date", "end_date")
        if params.country is not None and not params.country.strip():
            raise _query_validation_error("country")
        if params.calendar_id is not None:
            if not _INTEGER_LIST.fullmatch(params.calendar_id):
                raise _query_validation_error("calendar_id")
            if any(int(value) <= 0 for value in params.calendar_id.split(",")):
                raise _query_validation_error("calendar_id")
            if any(
                value is not None
                for value in (
                    params.country,
                    params.start_date,
                    params.end_date,
                    params.group,
                    params.importance,
                )
            ):
                raise _query_validation_error("calendar_id")
        if params.importance is not None and params.group is not None:
            raise _query_validation_error("importance", "group")
        return params

    def extract_data(self, params: _EconomicCalendarQuery, ctx: FetchContext) -> tuple[object, ...]:
        """Route through a documented path and reuse the governed JSON fetch lifecycle."""
        if type(params) is not self.query_model:
            raise _query_validation_error("query")
        inner_transport = self.http_transport or _http_get_json

        def routed_transport(
            url: str,
            query: dict[str, str],
            *,
            timeout: float,
            source: str,
            headers: dict[str, str] | None = None,
        ) -> HttpResponse:
            response = inner_transport(
                url,
                query,
                timeout=timeout,
                source=source,
                headers=headers,
            )
            if not 200 <= response.status < 300:
                return response
            return HttpResponse(
                response.status,
                _adapt_document(response.document),
                response.payload,
            )

        batches = _calendar_id_batches(params) if params.calendar_id is not None else (params,)
        pages: list[object] = []
        for batch in batches:
            request_spec = _request_spec(batch)
            if _request_url_length(batch, request_spec) > TRADINGECONOMICS_MAX_URL_CHARS:
                raise _query_validation_error("calendar_id" if batch.calendar_id else "country")
            pages.extend(
                fetch_pages(
                    request_spec,
                    batch,
                    ctx,
                    transport=routed_transport,
                    source=SOURCE,
                )
            )
        return tuple(pages)

    def transform_data(
        self, raw: object, params: _EconomicCalendarQuery
    ) -> tuple[TradingEconomicsEconomicCalendar, ...]:
        """Normalize the provider rows and enforce this module's named contract class."""
        rows = super().transform_data(raw, params)
        result: list[TradingEconomicsEconomicCalendar] = []
        for row in rows:
            if isinstance(row, TradingEconomicsEconomicCalendar):
                result.append(row)
            else:
                result.append(TradingEconomicsEconomicCalendar.model_validate(row.model_dump()))
        return tuple(result)


